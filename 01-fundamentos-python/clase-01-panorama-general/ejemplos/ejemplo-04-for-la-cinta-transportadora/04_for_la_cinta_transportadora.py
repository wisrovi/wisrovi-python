lista_compras = ["Manzanas 🍎", "Leche 🥛", "Pan 🍞", "Café ☕"]

print("📦 Iniciando empaque automático de productos...")

for producto in lista_compras:
    print("-> Empacando:", producto)

print("✅ Todos los productos han sido empacados.")

